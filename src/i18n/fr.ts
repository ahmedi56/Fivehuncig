/** "je" + verbe, avec élision devant une voyelle ou un h muet ; ne double pas un "je" déjà écrit. */
function je(action: string): string {
  const t = lowerStart(action);
  if (/^(je\s|j['’])/i.test(t)) return isolate(t);
  return /^[aeiouyhàâäéèêëîïôöûùü]/i.test(t) ? `j’${isolate(t)}` : `je ${isolate(t)}`;
}

/** "si" + proposition, avec élision devant "il"/"ils". */
function si(trigger: string): string {
  const t = lowerStart(trigger);
  return /^ils?\b/i.test(t) ? `S’${isolate(t)}` : `Si ${isolate(t)}`;
}

function lowerStart(s: string): string {
  const t = s.trim().replace(/\.$/, '');
  if (/^[A-ZÀ-Ý]{2}/.test(t)) return t;
  return t.charAt(0).toLowerCase() + t.slice(1);
}

